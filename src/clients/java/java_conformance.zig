const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Formatter = conformance.Formatter;

const line_width_max = 100;

// Mirrors `big_integer.fields` in `java_bindings.zig` — fields here become
// `BigInteger`, others `byte[]`. Maybe enforce at comptime later
const big_integer_fields = [_][]const u8{
    "credits_posted",
    "credits_pending",
    "debits_posted",
    "debits_pending",
    "amount",
};

pub fn main() !void {
    const formatter = Formatter.init(conformance.allocator(), .{
        .indent_width = 4,
    });

    const tests = try conformance.parse(formatter.arena);

    var stdout = std.io.bufferedWriter(std.io.getStdOut().writer());
    try emit(formatter, stdout.writer().any(), tests);
    try stdout.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => false,
    };
}

