            }
            try emit_case(formatter, writer, case);
            try formatter.write_indent(writer, .{});
            try writer.writeAll("}\n");
        }
    }
    try emit_server(writer);
    try writer.writeAll("}\n");
}

fn emit_case(
    formatter: Formatter,
    writer: std.io.AnyWriter,
    case: ast.Case,
) !void {
    var scope = Scope.init(formatter);
    var emitted = false;
    const consumed = try formatter.arena.alloc(bool, case.steps.len);
    @memset(consumed, false);
    for (case.steps, 0..) |step, index| {
        if (consumed[index]) continue;
        if (emitted and starts_operation(step)) try writer.writeAll("\n");
        if (step == .binding and step.binding.value == .index and
            !scope.id_arrays.contains(step.binding.value.index.reference))
        {
            try emit_row_group(writer, &scope, case.steps, index, consumed);
        } else {
            try emit_step(writer, &scope, step);
        }
        emitted = true;
    }
}

// Each request and the statements that build and check it form a paragraph, the way the
// hand-written integration tests are laid out.
fn starts_operation(step: ast.Step) bool {
    return switch (step) {
        .call => true,
        .binding => |binding| binding.value == .call,
        .assertion => |assertion| assertion == .fail,
    };
}

// Java has no row type: a result batch is its own cursor. So an indexed binding never becomes a
// local. The rows a case names are walked with `next()`, each row's assertions grouped behind its
// own advance, the way `IntegrationTest` reads a batch.
fn emit_row_group(
    writer: std.io.AnyWriter,
    scope: *Scope,
    steps: []const ast.Step,
    start: usize,
    consumed: []bool,
) !void {
    const formatter = scope.formatter;
    const origin = steps[start].binding.value.index;
    const batch = try formatter.to_case(.camelCase, origin.reference);

    var rows = std.ArrayList([]const u8).init(formatter.arena);
    for (steps[start..], start..) |step, index| {
        if (step != .binding or step.binding.value != .index) continue;
        if (!std.mem.eql(u8, step.binding.value.index.reference, origin.reference)) continue;
        assert(step.binding.value.index.index == rows.items.len);
        try rows.append(step.binding.name);
        consumed[index] = true;
    }

    try scope.walk(writer, batch);
    for (rows.items) |row| {
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("assertTrue({s}.next());\n", .{batch});
        for (steps, 0..) |step, index| {
            if (step != .assertion) continue;
            var comparison: ast.Assertion.FieldComparison = undefined;
            var greater_than = false;
            switch (step.assertion) {
                .equal_field => |value| comparison = value,
                .greater_than => |value| {
                    comparison = value;
                    greater_than = true;
                },
                else => continue,
            }
            if (!std.mem.eql(u8, comparison.reference, row)) continue;
            consumed[index] = true;

            const property = try formatter.to_case(.PascalCase, comparison.field.name);
            const value = try render_field_value(formatter, comparison.field);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            if (greater_than) {
                try writer.print("assertTrue({s}.get{s}() > {s});\n", .{ batch, property, value });
            } else {
                try writer.print("{s}({s}, {s}.get{s}());\n", .{
                    assert_function(comparison.field),
                    value,
                    batch,
                    property,
                });
            }
        }
    }
}

// Bound record literals are inlined at each use, since Java has no standalone event type: a
// record only exists as a row of a batch. Generated ids are hoisted to locals first, so a record
// reused across two calls carries the same id both times.
const Scope = struct {
    formatter: Formatter,
    records: std.StringHashMap(ast.Record),
    id_arrays: std.StringHashMap(void),
    walked: std.StringHashMap(void),

    fn init(formatter: Formatter) Scope {
        return .{
            .formatter = formatter,
            .records = std.StringHashMap(ast.Record).init(formatter.arena),
            .id_arrays = std.StringHashMap(void).init(formatter.arena),
            .walked = std.StringHashMap(void).init(formatter.arena),
        };
    }

    // A batch is a cursor, so a second pass over one has to rewind first.
    fn walk(scope: *Scope, writer: std.io.AnyWriter, batch: []const u8) !void {
        const entry = try scope.walked.getOrPut(batch);
        if (!entry.found_existing) return;
        const formatter = scope.formatter;
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("{s}.beforeFirst();\n", .{batch});
    }
};

fn emit_step(writer: std.io.AnyWriter, scope: *Scope, step: ast.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(writer, scope, binding),
        .call => |call| try emit_call(writer, scope, call, .{}),
        .assertion => |assertion| try emit_assertion(writer, scope, assertion),
    }
}

fn emit_binding(writer: std.io.AnyWriter, scope: *Scope, binding: ast.Binding) !void {
    const formatter = scope.formatter;
    const name = try formatter.to_case(.camelCase, binding.name);
    switch (binding.value) {
        .generate_id => {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("final var {s} = UInt128.id();\n", .{name});
        },
        .generate_ids => |count| {
            try scope.id_arrays.put(binding.name, {});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("final var {s} = new byte[{d}][];\n", .{ name, count });
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for (int index = 0; index < {d}; index++) {{\n", .{count});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.print("{s}[index] = UInt128.id();\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .index => |index| {
            const reference = try formatter.to_case(.camelCase, index.reference);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("final var {s} = {s}[{d}];\n", .{ name, reference, index.index });
        },
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                const value = try render_uint128(formatter, record.fields[0].value.integer);
                try emit_assignment(formatter, writer, formatter.statement_level, name, value);
            },
            .Account, .Transfer => {
                try scope.records.put(binding.name, try hoist_record(writer, scope, name, record));
            },
            // Flags cannot be bound on their own, and result types are never written by hand.
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .TransferFlags,
            => unreachable,
        },
        .call => |call| try emit_call(writer, scope, call, .{ .binding = name }),
        .integer, .boolean, .enum_literal, .reference => unreachable,
    }
}

// Emits a local for every generated id in the record, returning the record with those fields
// rewritten to reference the local.
fn hoist_record(
    writer: std.io.AnyWriter,
    scope: *Scope,
    name: []const u8,
    record: ast.Record,
) !ast.Record {
    const formatter = scope.formatter;
    const fields = try formatter.arena.alloc(ast.Field, record.fields.len);
    for (record.fields, 0..) |field, index| {
        if (field.value != .generate_id) {
            fields[index] = field;
            continue;
        }
        const local = try std.fmt.allocPrint(formatter.arena, "{s}{s}", .{
            name,
            try formatter.to_case(.PascalCase, field.name),
        });
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("final var {s} = UInt128.id();\n", .{local});
        fields[index] = .{ .name = field.name, .value = .{ .reference = local }, .type = field.type };
    }
    return .{ .type = record.type, .fields = fields };
}

fn emit_call(
    writer: std.io.AnyWriter,
    scope: *Scope,
    call: ast.Call,
    options: struct {
        binding: ?[]const u8 = null,
        expect_error: bool = false,
    },
) !void {
    const formatter = scope.formatter;
    if (call.concurrency > 1) {
        assert(options.binding == null);
        // A `RuntimeException` thrown from `Thread.run()` is delivered to the uncaught
        // handler and dropped, so each thread captures into `exceptions` for a post-join
        // rethrow — the same shape as `IntegrationTest.TransferTask` storing `.exception`.
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("final var threads = new Thread[{d}];\n", .{call.concurrency});
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("final var exceptions = new Exception[{d}];\n", .{call.concurrency});
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print(
            "for (int index = 0; index < {d}; index++) {{\n",
            .{call.concurrency},
        );
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("final var threadIndex = index;\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("threads[index] = new Thread(() -> {\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
        try writer.writeAll("try {\n");

        var thread_scope = Scope.init(formatter);
        try emit_operation(writer, &thread_scope, call, .{
            .indent_level = formatter.statement_level + 3,
            .error_action = .rethrow,
        });

        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
        try writer.writeAll("} catch (Exception exception) {\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 3 });
        try writer.writeAll("exceptions[threadIndex] = exception;\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
        try writer.writeAll("}\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("});\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("threads[index].start();\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("}\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("for (final var thread : threads) {\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("thread.join(Duration.ofSeconds(60).toMillis());\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll(
            "assertTrue(\"Worker did not terminate within 60 seconds\", !thread.isAlive());\n",
        );
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("}\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("for (final var exception : exceptions) {\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("if (exception != null)\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
        try writer.writeAll("throw exception;\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("}\n");
        return;
    }

    try emit_operation(writer, scope, call, .{
        .indent_level = formatter.statement_level,
        .binding = options.binding,
        .error_action = if (options.expect_error) .expected else .propagate,
    });
}

const ErrorAction = enum { propagate, rethrow, expected };

fn emit_operation(
    writer: std.io.AnyWriter,
    scope: *Scope,
    call: ast.Call,
    options: struct {
        indent_level: u32,
        binding: ?[]const u8 = null,
        error_action: ErrorAction,
    },
) !void {
    const formatter = scope.formatter;
    switch (call.name) {
        .close_client => {
            assert(options.binding == null);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("client.close();\n");
            return;
        },
        .sleep_ms => {
            assert(options.binding == null);
            assert(call.arguments.len == 1);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print("Thread.sleep({s});\n", .{call.arguments[0].integer});
            return;
        },
        else => {},
    }

    // A call whose result the corpus binds names its input after that binding; one whose result
    // is discarded gets a block, so the plain name is free to repeat.
    const scoped = options.binding == null;
    const indent_level = options.indent_level + @intFromBool(scoped);
    if (scoped) {
        try formatter.write_indent(writer, .{ .level = options.indent_level });
        try writer.writeAll("{\n");
    }

    // The argument is built into a local first, so that `assertThrows` can capture it: a lambda
    // may only close over effectively final locals.
    const argument = try emit_argument(writer, scope, call, indent_level, options.binding);

    try formatter.write_indent(writer, .{ .level = indent_level });
    if (options.error_action == .expected) {
        try writer.print("assertThrows(Exception.class, () -> client.{s}({s}));\n", .{
            java_operation_name(call.name),
            argument,
        });
    } else {
        if (options.binding) |binding| try writer.print("final var {s} = ", .{binding});
        try writer.print("client.{s}({s});\n", .{ java_operation_name(call.name), argument });
    }

    if (scoped) {
        try formatter.write_indent(writer, .{ .level = options.indent_level });
        try writer.writeAll("}\n");
    }
}

fn local_name(
    formatter: Formatter,
    binding: ?[]const u8,
    suffix: []const u8,
    unbound: []const u8,
) ![]const u8 {
    const name = binding orelse return unbound;
    return std.fmt.allocPrint(formatter.arena, "{s}{s}", .{ name, suffix });
}

fn emit_argument(
    writer: std.io.AnyWriter,
    scope: *Scope,
    call: ast.Call,
    indent_level: u32,
    binding: ?[]const u8,
) ![]const u8 {
    const formatter = scope.formatter;
    switch (call.name) {
        .create_accounts, .create_transfers => {
            const accounts = call.name == .create_accounts;
            const batch_type = if (accounts) "AccountBatch" else "TransferBatch";
            const name = try local_name(
                formatter,
                binding,
                "Batch",
                if (accounts) "accountsBatch" else "transfersBatch",
            );
            try formatter.write_indent(writer, .{ .level = indent_level });
            try writer.print("final var {s} = new {s}({d});\n", .{
                name,
                batch_type,
                call.arguments.len,
            });
            for (call.arguments) |argument| {
                const record = switch (argument) {
                    .record => |record| record,
                    .reference => |reference| scope.records.get(reference).?,
                    else => unreachable,
                };
                try emit_record_into(writer, formatter, record, name, indent_level);
            }
            return name;
        },
        .lookup_accounts, .lookup_transfers => {
            const name = try local_name(formatter, binding, "Batch", "idsBatch");
            try formatter.write_indent(writer, .{ .level = indent_level });
            try writer.print("final var {s} = new IdBatch({d});\n", .{ name, call.arguments.len });
            for (call.arguments) |argument| {
                try formatter.write_indent(writer, .{ .level = indent_level });
                try writer.print("{s}.add({s});\n", .{ name, try render_id(formatter, argument) });
            }
            return name;
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const filter = call.arguments[0].record;
            const name = try local_name(formatter, binding, "Filter", "filter");
            try formatter.write_indent(writer, .{ .level = indent_level });
            try writer.print("final var {s} = new {s}();\n", .{ name, @tagName(filter.type) });
            for (filter.fields) |field| {
                try emit_filter_field(writer, formatter, field, name, indent_level);
            }
            return name;
        },
        .close_client, .sleep_ms => unreachable,
    }
}

fn emit_record_into(
    writer: std.io.AnyWriter,
    formatter: Formatter,
    record: ast.Record,
    batch: []const u8,
    indent_level: u32,
) !void {
    try formatter.write_indent(writer, .{ .level = indent_level });
    try writer.print("{s}.add();\n", .{batch});
    for (record.fields) |field| {
        try emit_setter(
            formatter,
            writer,
            indent_level,
            batch,
            try formatter.to_case(.PascalCase, field.name),
            try render_field_value(formatter, field),
        );
    }
}

// Filters expose their flags as boolean setters (`setDebits(true)`) rather than a flags word.
fn emit_filter_field(
    writer: std.io.AnyWriter,
    formatter: Formatter,
    field: ast.Field,
    name: []const u8,
    indent_level: u32,
) !void {
    if (field.value == .record and ast.Record.is_flags(field.value.record.type)) {
        for (field.value.record.fields) |flag| {
            assert(flag.value == .boolean and flag.value.boolean);
            try formatter.write_indent(writer, .{ .level = indent_level });
            try writer.print("{s}.set{s}(true);\n", .{
                name,
                try formatter.to_case(.PascalCase, flag.name),
            });
        }
        return;
    }
    try emit_setter(
        formatter,
        writer,
        indent_level,
        name,
        try formatter.to_case(.PascalCase, field.name),
        try render_field_value(formatter, field),
    );
}

// Eclipse breaks an over-long statement onto a continuation line indented two levels further.
fn emit_assignment(
    formatter: Formatter,
    writer: std.io.AnyWriter,
    indent_level: u32,
    name: []const u8,
    value: []const u8,
) !void {
    const width = indent_level * formatter.indent_width + "final var ".len + name.len +
        " = ".len + value.len + ";".len;
    try formatter.write_indent(writer, .{ .level = indent_level });
    if (width <= line_width_max) {
        try writer.print("final var {s} = {s};\n", .{ name, value });
        return;
    }
    try writer.print("final var {s} =\n", .{name});
    try formatter.write_indent(writer, .{ .level = indent_level + 2 });
    try writer.print("{s};\n", .{value});
}

fn emit_setter(
    formatter: Formatter,
    writer: std.io.AnyWriter,
    indent_level: u32,
    target: []const u8,
    property: []const u8,
    value: []const u8,
) !void {
    const width = indent_level * formatter.indent_width + target.len + ".set".len + property.len +
        "(".len + value.len + ");".len;
    try formatter.write_indent(writer, .{ .level = indent_level });
    if (width <= line_width_max) {
        try writer.print("{s}.set{s}({s});\n", .{ target, property, value });
        return;
    }

    // A flags word is the only setter argument that overflows; Eclipse breaks before each `|`.
    var count: usize = 1;
    var counter = std.mem.splitSequence(u8, value, " | ");
    _ = counter.first();
    while (counter.next()) |_| count += 1;

    var operands = std.mem.splitSequence(u8, value, " | ");
    try writer.print("{s}.set{s}({s}\n", .{ target, property, operands.first() });
    var index: usize = 1;
    while (operands.next()) |operand| : (index += 1) {
        try formatter.write_indent(writer, .{ .level = indent_level + 2 });
        try writer.print("| {s}{s}\n", .{ operand, if (index + 1 == count) ");" else "" });
    }
}

fn emit_assertion(writer: std.io.AnyWriter, scope: *Scope, assertion: ast.Assertion) !void {
    const formatter = scope.formatter;
    switch (assertion) {
        .equal => |equal| {
            const actual = try formatter.to_case(.camelCase, equal.actual);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assertEquals({d}, {s}.getLength());\n", .{
                equal.expected.len,
                actual,
            });
            try scope.walk(writer, actual);
            for (equal.expected) |record| {
                try formatter.write_indent(writer, .{ .level = formatter.statement_level });
                try writer.print("assertTrue({s}.next());\n", .{actual});
                for (record.fields) |field| {
                    try emit_field_equal(writer, formatter, field, actual);
                }
            }
        },
        .empty => |actual| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assertEquals(0, {s}.getLength());\n", .{
                try formatter.to_case(.camelCase, actual),
            });
        },
        .unique => |ids| {
            const name = try formatter.to_case(.camelCase, ids);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("final var seen = new HashSet<BigInteger>();\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for (final var id : {s}) {{\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.writeAll("assertTrue(seen.add(UInt128.asBigInteger(id)));\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .ascending => |ids| {
            const name = try formatter.to_case(.camelCase, ids);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for (int index = 1; index < {s}.length; index++) {{\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.print(
                "assertTrue(UInt128.asBigInteger({s}[index - 1])\n",
                .{name},
            );
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 3 });
            try writer.print(".compareTo(UInt128.asBigInteger({s}[index])) < 0);\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .equal_field => |comparison| {
            const expected = try render_field_value(formatter, comparison.field);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("{s}({s}, {s});\n", .{
                assert_function(comparison.field),
                expected,
                try render_field_reference(formatter, comparison),
            });
        },
        .greater_than => |comparison| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assertTrue({s} > {s});\n", .{
                try render_field_reference(formatter, comparison),
                try render_field_value(formatter, comparison.field),
            });
        },
        .fail => |call| try emit_call(writer, scope, call, .{ .expect_error = true }),
    }
}

fn emit_field_equal(
    writer: std.io.AnyWriter,
    formatter: Formatter,
    field: ast.Field,
    actual: []const u8,
) !void {
    try formatter.write_indent(writer, .{ .level = formatter.statement_level });
    try writer.print("{s}({s}, {s}.get{s}());\n", .{
        assert_function(field),
        try render_field_value(formatter, field),
        actual,
        try formatter.to_case(.PascalCase, field.name),
    });
}

fn assert_function(field: ast.Field) []const u8 {
    if (is_byte_array(field)) return "assertArrayEquals";
    return "assertEquals";
}

fn is_byte_array(field: ast.Field) bool {
    if (field.type != .int or field.type.int != 128) return false;
    return !is_big_integer(field.name);
}

fn is_big_integer(field_name: []const u8) bool {
    for (big_integer_fields) |name| {
        if (std.mem.eql(u8, name, field_name)) return true;
    }
    return false;
}

fn render_field_reference(
    formatter: Formatter,
    comparison: ast.Assertion.FieldComparison,
) ![]const u8 {
    return std.fmt.allocPrint(formatter.arena, "{s}.get{s}()", .{
        try formatter.to_case(.camelCase, comparison.reference),
        try formatter.to_case(.PascalCase, comparison.field.name),
    });
}

fn render_field_value(formatter: Formatter, field: ast.Field) ![]const u8 {
    switch (field.value) {
        .enum_literal => |literal| {
            return std.fmt.allocPrint(formatter.arena, "{s}.{s}", .{
                field.type.enum_name,
                try formatter.to_case(.PascalCase, literal),
            });
        },
        .record => |flags| {
            assert(ast.Record.is_flags(flags.type));
            var text = std.ArrayList(u8).init(formatter.arena);
            for (flags.fields, 0..) |flag, index| {
                assert(flag.value == .boolean and flag.value.boolean);
                if (index > 0) try text.appendSlice(" | ");
                try text.writer().print("{s}.{s}", .{
                    @tagName(flags.type),
                    try formatter.to_case(.UPPER_CASE, flag.name),
                });
            }
            return text.items;
        },
        .integer => |text| {
            const bits = field.type.int;
            if (bits == 128) {
                if (is_big_integer(field.name)) return render_big_integer(formatter, text);
                return render_uint128(formatter, text);
            }
            // A 64-bit literal overflows Java's `int` without the suffix.
            if (bits == 64) return std.fmt.allocPrint(formatter.arena, "{s}L", .{text});
            return text;
        },
        .generate_id => return "UInt128.id()",
        .reference => |name| return formatter.to_case(.camelCase, name),
        .index => |index| {
            return std.fmt.allocPrint(formatter.arena, "{s}[{d}]", .{
                try formatter.to_case(.camelCase, index.reference),
                index.index,
            });
        },
        .boolean => |value| return if (value) "true" else "false",
        .call, .generate_ids => unreachable,
    }
}

// Ids reach the client as `byte[]`, whatever shape they take in the corpus.
fn render_id(formatter: Formatter, expression: ast.Expression) ![]const u8 {
    switch (expression) {
        .generate_id => return "UInt128.id()",
        .reference => |name| return formatter.to_case(.camelCase, name),
        .integer => |text| return render_uint128(formatter, text),
        .index => |index| {
            return std.fmt.allocPrint(formatter.arena, "{s}[{d}]", .{
                try formatter.to_case(.camelCase, index.reference),
                index.index,
            });
        },
        .call, .generate_ids, .record, .boolean, .enum_literal => unreachable,
    }
}

fn render_uint128(formatter: Formatter, text: []const u8) ![]const u8 {
    const value = std.fmt.parseInt(u128, text, 10) catch unreachable;
    if (value <= std.math.maxInt(u64)) {
        return std.fmt.allocPrint(formatter.arena, "UInt128.asBytes({d}L)", .{value});
    }
    return std.fmt.allocPrint(
        formatter.arena,
        "UInt128.asBytes(new BigInteger(\"{d}\"))",
        .{value},
    );
}

fn render_big_integer(formatter: Formatter, text: []const u8) ![]const u8 {
    const value = std.fmt.parseInt(u128, text, 10) catch unreachable;
    if (value <= std.math.maxInt(u64)) {
        return std.fmt.allocPrint(formatter.arena, "BigInteger.valueOf({d}L)", .{value});
    }
    return std.fmt.allocPrint(formatter.arena, "new BigInteger(\"{d}\")", .{value});
}

fn java_operation_name(name: ast.Call.Name) []const u8 {
    return switch (name) {
        .create_accounts => "createAccounts",
        .create_transfers => "createTransfers",
        .lookup_accounts => "lookupAccounts",
        .lookup_transfers => "lookupTransfers",
        .get_account_transfers => "getAccountTransfers",
        .get_account_balances => "getAccountBalances",
        .query_accounts => "queryAccounts",
        .query_transfers => "queryTransfers",
        .close_client, .sleep_ms => unreachable,
    };
}

